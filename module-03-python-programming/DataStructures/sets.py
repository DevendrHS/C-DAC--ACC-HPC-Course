# sets--store unique values in a single variable
# Sets are mutable data types in Python.

my_set = {1, 2, 3, 4, 5}
print(my_set)


data = {10,10, 20, 30, "python", 40, True, 3.14, 50}# print only unique values
print(data)


## Adding an element to the set
data.add("Devendra")
print(data)

# set does not support indexing, slicing, or other sequence-like behavior.
